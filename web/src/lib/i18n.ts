// English wording where the key is not the text itself.
const EN: Dict = { 'Text {code} to {number}': 'Text {code} to {number}', 'By signing up, you agree to the {terms}': 'By signing up, you agree to the {terms}', 'Terms of Service (link)': 'Terms of Service' };
const DICTS: Record<string, Dict> = { hi, ta };
export const TRANSLATED = ['en', 'hi', 'ta'];
// Languages switched on. English only at launch (decided 30 Sep); the Hindi and Tamil
// translations above are kept for when they're switched on.
export const ENABLED = ['en'];

const LANG_KEY = 'phonemail.lang';
export function storedLanguage(): string {
  try {
    return localStorage.getItem(LANG_KEY) || 'en';
  } catch {
    return 'en';
  }
}
/** True once this browser has chosen a language (the first-visit language screen is done). */
export function hasChosenLanguage(): boolean {
  try {
    return localStorage.getItem(LANG_KEY) !== null;
  } catch {
    return true; // storage blocked: don't keep showing the language screen
  }
}
export function rememberLanguage(lang: string) {
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    /* private mode */
  }
}

export type T = (s: string, vars?: Record<string, string | number>) => string;

export function translator(lang: string): T {
  const dict = ENABLED.includes(lang) ? DICTS[lang] : undefined;
  return (s, vars) => {
    let out = dict?.[s] ?? EN[s] ?? s;
    if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
    out = out.replaceAll('{brand}', brand.name);
    return out;
  };
}

// useT: the translator for the signed-in person's language (or this browser's last one before sign-in).
export function useT(): T {
  const { user } = useSession();
  return translator(user?.language || storedLanguage());
}
